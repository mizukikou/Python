import os

# 定義目標檔案路徑
fName = 'c:/data/stu.txt'

# 1. 安全防禦：檢查該路徑是否為一個實際存在的檔案，避免後續開啟時程式崩潰
if os.path.isfile(fName):
    
    # 2. 開啟檔案：以 'a+' (追加寫入且可讀取) 模式開啟，並指定 UTF-8 編碼
    # 💡 提示：以 'a+' 模式開啟時，預設的檔案指針（游標）會自動停在檔案的最末端。
    with open(fName, 'a+', encoding='utf-8') as fa:
        
        # 3. 定位到第二行：強制將指針移動到第 16 個位元組（Byte）的位置
        # 🧮 計算原理：第一行「王一心, 85, 90\n」剛好佔用 16 位元組（中文2*3 + 英數符號8 + 換行2）
        # 移動後，指針會精準停在第二行「張三飛」的「張」字最前面
        fa.seek(19)
        
        # 4. 讀取第二行：從目前指針位置（第16位元組）往後讀取一整行，直到遇到換行符號
        str1 = fa.readline() 
        print(str1, end='')  # 螢幕印出：張三飛, 75, 87
        
        # 5. 倒帶回最開頭：將檔案指針重置回整個檔案的最開頭（第 0 個位元組位置）
        fa.seek(0)
        
        # 6. 讀取第一行：從檔案最開頭（第0位元組）重新往後讀取一整行
        str1 = fa.readline()
        print(str1, end='')  # 螢幕印出：王一心, 85, 90
        
else:
    # 如果在指定路徑找不到該檔案，則印出 None
    print(None)
    
#現代 UTF-8 編碼下，一個中文字固定佔 3 位元組。
